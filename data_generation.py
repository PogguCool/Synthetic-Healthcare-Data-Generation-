def fitness_function(params, num_samples, G):
    """
    Evaluates the quality of generated synthetic data based on multiple criteria
    Returns a fitness score between 0 and 1
    """
    try:
        # Generate synthetic data
        synthetic_data = generate_synthetic_data(num_samples, G, params)
        
        # Initialize weights for different components
        weights = {
            'age_correlation': 0.25,
            'feature_consistency': 0.25,
            'disease_distribution': 0.25,
            'risk_correlation': 0.25
        }
        
        scores = {}
        
        # 1. Age-Disease Correlation Score
        scores['age_correlation'] = evaluate_age_correlation(synthetic_data)
        
        # 2. Feature Consistency Score
        scores['feature_consistency'] = evaluate_feature_consistency(synthetic_data)
        
        # 3. Disease Distribution Score
        scores['disease_distribution'] = evaluate_disease_distribution(synthetic_data)
        
        # 4. Risk Factor Correlation Score
        scores['risk_correlation'] = evaluate_risk_correlation(synthetic_data)
        
        # Calculate weighted fitness score
        fitness = sum(scores[key] * weights[key] for key in weights.keys())
        
        return fitness

    except Exception as e:
        print(f"Error in fitness calculation: {e}")
        return 0.0

def evaluate_age_correlation(data):
    """Evaluates if age distributions match expected patterns for each disease"""
    try:
        correct_ages = 0
        total_cases = len(data)
        
        for _, row in data.iterrows():
            disease = row['Rare_Disease']
            age = row['Age']
            age_of_onset = row['Age_of_Onset']
            
            # Check if age is appropriate for the disease
            if age >= age_of_onset and age <= age_of_onset + 50:
                correct_ages += 1
                
        return correct_ages / total_cases
    except:
        return 0.5

def evaluate_feature_consistency(data):
    """Evaluates if disease features are consistent with medical knowledge"""
    try:
        consistent_features = 0
        total_features = 0
        
        for _, row in data.iterrows():
            disease = row['Rare_Disease']
            features = set(row['Features'].split(', '))
            expected_features = set(disease_features.get(disease, []))
            
            if features.issubset(expected_features):
                consistent_features += len(features)
            total_features += len(features)
            
        return consistent_features / total_features if total_features > 0 else 0.5
    except:
        return 0.5

def evaluate_disease_distribution(data):
    """Evaluates if disease distribution is balanced"""
    try:
        disease_counts = data['Rare_Disease'].value_counts()
        expected_count = len(data) / len(data['Rare_Disease'].unique())
        
        # Calculate deviation from uniform distribution
        deviation = 1 - (abs(disease_counts - expected_count).mean() / expected_count)
        return max(0, deviation)
    except:
        return 0.5

def evaluate_risk_correlation(data):
    """Evaluates if risk factors correlate with severity and age"""
    try:
        # Calculate correlation between Risk_Factor and other metrics
        risk_age_corr = data['Risk_Factor'].corr(data['Age'])
        risk_severity_corr = data['Risk_Factor'].corr(data['Severity_Score'])
        
        # Average the correlations (should be positive)
        return (abs(risk_age_corr) + abs(risk_severity_corr)) / 2
    except:
        return 0.5

