def calculate_risk_factor(row):
    """Calculate risk factor based on multiple parameters"""
    base_risk = 0
    
    # Age factor
    if row['Age'] > 60:
        base_risk += 3
    elif row['Age'] > 40:
        base_risk += 2
    elif row['Age'] > 20:
        base_risk += 1
        
    # Death rate factor
    base_risk += int(row['Death_Rate'] * 5)
    
    # Severity factor
    base_risk += row['Severity_Score'] // 2
    
    # Family history factor
    if row['Family_History'] == 'Yes':
        base_risk += 2
        
    # Normalize risk factor to 1-10 scale
    risk_factor = min(10, max(1, base_risk))
    
    return risk_factor

